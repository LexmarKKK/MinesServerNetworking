namespace MinesServer.Data;

/// <summary>
/// Гарнитура текста элемента окна. Значения фиксированы порядком — часть
/// контракта провода: клиент отображает идентификатор на шрифты своей темы.
/// </summary>
public enum FontId : byte
{
    /// Основной текст (в клиенте — Onest).
    Text,
    /// Дисплейная гарнитура заголовков (в клиенте — Exo 2).
    Display,
    /// Моноширинная гарнитура чисел и капса (в клиенте — JetBrains Mono).
    Mono,
}
